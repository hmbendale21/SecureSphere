const sidebarToggle = document.getElementById("sidebarToggle");
const sidebarMenu = document.getElementById("sidebarMenu");
const sidebarArrow = document.getElementById("sidebarArrow");

sidebarToggle.addEventListener("click", () => {

    sidebarMenu.classList.toggle("show");

    sidebarArrow.className = sidebarMenu.classList.contains("show")
        ? "bi bi-chevron-down"
        : "bi bi-chevron-right";

});


/* ======================================
   DOM Elements
====================================== */

const inputText = document.getElementById("inputText");

const charCount = document.getElementById("charCount");

const generateBtn = document.getElementById("generateBtn");

const clearBtn = document.getElementById("clearBtn");

const copyBtn = document.getElementById("copyBtn");

const downloadBtn = document.getElementById("downloadBtn");

const outputBox = document.getElementById("hashOutput");

const operationInputs = document.querySelectorAll(
    'input[name="operation"]'
);


/* ======================================
   Character Counter
====================================== */

inputText.addEventListener("input", () => {

    charCount.textContent =
        `Characters : ${inputText.value.length}`;

});


/* ======================================
   Toast Notification
====================================== */

const liveToast = document.getElementById("liveToast");

const toastMessage = document.getElementById("toastMessage");

const toast = new bootstrap.Toast(liveToast);

function showToast(message){

    toastMessage.textContent = message;

    toast.show();

}


/* ======================================
   URL Encode / Decode
====================================== */

generateBtn.addEventListener("click", () => {

    const text = inputText.value.trim();

    if(text === ""){

        showToast("Please enter some text.");

        return;

    }

    const operation = document.querySelector(
        'input[name="operation"]:checked'
    ).value;

    generateBtn.disabled = true;

    generateBtn.innerHTML = `
        <span class="spinner-border spinner-border-sm me-2"></span>
        Processing...
    `;

    setTimeout(() => {

        try{

            let output = "";

            if(operation === "encode"){

                output = encodeURIComponent(text);

            }

            else{

                output = decodeURIComponent(text);

            }

            outputBox.value = output;

            outputBox.focus();

            outputBox.select();

            showToast("Operation completed successfully.");

        }

        catch(error){

            showToast("Invalid encoded URL.");

        }

        finally{

            generateBtn.disabled = false;

            generateBtn.innerHTML = `
                <i class="bi bi-lightning-charge-fill"></i>
                Process Text
            `;

        }

    },150);

});


/* ======================================
   Copy Output
====================================== */

copyBtn.addEventListener("click", async () => {

    const output = outputBox.value.trim();

    if (output === "") {

        showToast("Nothing to copy.");

        return;

    }

    try {

        await navigator.clipboard.writeText(output);

        showToast("Copied successfully!");

        const originalText = copyBtn.innerHTML;

        copyBtn.innerHTML = `
            <i class="bi bi-check-circle-fill"></i>
            Copied!
        `;

        copyBtn.classList.remove("btn-success");
        copyBtn.classList.add("btn-primary");

        setTimeout(() => {

            copyBtn.innerHTML = originalText;

            copyBtn.classList.remove("btn-primary");
            copyBtn.classList.add("btn-success");

        }, 2000);

    }

    catch {

        showToast("Failed to copy.");

    }

});


/* ======================================
   Clear
====================================== */

clearBtn.addEventListener("click", () => {

    inputText.value = "";

    outputBox.value = "";

    charCount.textContent = "Characters : 0";

    document.querySelector(
        'input[value="encode"]'
    ).checked = true;

    inputText.focus();

    updateInfo();

    showToast("Cleared successfully.");

});


/* ======================================
   Download
====================================== */

downloadBtn.addEventListener("click", () => {

    const output = outputBox.value.trim();

    if (output === "") {

        showToast("Nothing to download.");

        return;

    }

    const operation = document.querySelector(
        'input[name="operation"]:checked'
    ).value;

    const report = `

SecureSphere URL Encoder / Decoder

---------------------------------------

Operation :

${operation.toUpperCase()}

Result :

${output}

Generated On :

${new Date().toLocaleString()}

Generated By :

SecureSphere

`;

    const blob = new Blob(

        [report],

        {

            type: "text/plain"

        }

    );

    const url = URL.createObjectURL(blob);

    const link = document.createElement("a");

    link.href = url;

    link.download = `${operation}-url.txt`;

    link.click();

    URL.revokeObjectURL(url);

    showToast("Downloaded successfully!");

});


/* ======================================
   Keyboard Shortcut
====================================== */

inputText.addEventListener("keydown", (e) => {

    if (e.ctrlKey && e.key === "Enter") {

        generateBtn.click();

    }

});


/* ======================================
   Information Cards
====================================== */

const operationType = document.getElementById("operationType");

const outputFormat = document.getElementById("outputFormat");

const purpose = document.getElementById("purpose");

const usage = document.getElementById("usage");

const securityTip = document.getElementById("securityTip");

function updateInfo() {

    const operation = document.querySelector(
        'input[name="operation"]:checked'
    ).value;

    if (operation === "encode") {

        operationType.textContent = "URL Encode";

        outputFormat.textContent = "Percent Encoded";

        purpose.textContent = "Safe URL Transmission";

        usage.textContent = "Query Parameters, REST APIs";

        securityTip.innerHTML = `

<strong>Important:</strong>

URL Encoding is NOT encryption.

It simply converts reserved characters into a browser-safe format.

`;

    }

    else {

        operationType.textContent = "URL Decode";

        outputFormat.textContent = "Decoded URL";

        purpose.textContent = "Restore Original URL";

        usage.textContent = "Read Encoded URLs";

        securityTip.innerHTML = `

<strong>Decoded Successfully.</strong>

Verify the decoded URL before opening or sharing it.

`;

    }

}

operationInputs.forEach(input => {

    input.addEventListener(

        "change",

        updateInfo

    );

});

updateInfo();
